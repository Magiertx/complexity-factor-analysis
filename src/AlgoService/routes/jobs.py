"""Job execution management, tracking, deletion, and export endpoints."""

from __future__ import annotations

import asyncio
from typing import Any

from fastapi import APIRouter, HTTPException, Depends
from fastapi.concurrency import run_in_threadpool
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

import jobs_db
from config import validate_job_id, sse_manager, broadcast_jobs_update, get_session_id
from factor_analysis import storage as datasets
from zip_export import download_job_artifacts as _download_job_artifacts


class NotesUpdate(BaseModel):
    notes: str | None = Field(default=None, max_length=2000)

router = APIRouter()


@router.get("/jobs")
async def list_jobs(session_id: str = Depends(get_session_id)) -> dict[str, Any]:
    """List all registered jobs for the current session."""
    jobs = await jobs_db.list_jobs(session_id)
    return {"jobs": jobs}


@router.get("/jobs/events")
async def jobs_events_endpoint() -> StreamingResponse:
    """Server-Sent Events (SSE) endpoint broadcasting job status updates in real-time."""
    async def event_generator():
        queue = sse_manager.connect()
        try:
            # Send initial keep-alive comment
            yield "data: initial\n\n"
            while True:
                # Wait for broadcast updates
                await queue.get()
                yield "data: update\n\n"
        except asyncio.CancelledError:
            pass
        finally:
            sse_manager.disconnect(queue)

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no"
        }
    )


@router.get("/jobs/{job_id}")
async def get_job_detail(job_id: str, session_id: str = Depends(get_session_id)) -> dict[str, Any]:
    """Retrieve detailed state and results of a job."""
    validate_job_id(job_id)
    job = await jobs_db.read_job(job_id, session_id)
    if not job or "created_at" not in job:
        raise HTTPException(status_code=404, detail="Job not found")
    return job


def _delete_dataset_of(job: dict[str, Any], session_id: str) -> None:
    """A factor-analysis dataset goes with the job that computed it."""
    dataset_id = job["params"].get("dataset_id")
    if not job["algorithm_id"].startswith("_dataset:") or not dataset_id:
        return
    try:
        datasets.delete(session_id, dataset_id)
    except ValueError:
        pass


@router.delete("/jobs/{job_id}")
async def delete_job(job_id: str, session_id: str = Depends(get_session_id)) -> dict[str, str]:
    """Delete a job and its associated workspace artifacts, and the dataset of a dataset job."""
    validate_job_id(job_id)
    job = await jobs_db.read_job(job_id, session_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")
    await jobs_db.delete_job_file(job_id, session_id)
    await run_in_threadpool(_delete_dataset_of, job, session_id)
    await broadcast_jobs_update()
    return {"status": "deleted"}


@router.delete("/jobs")
async def delete_all_jobs(session_id: str = Depends(get_session_id)) -> dict[str, str]:
    """Delete all jobs from database and clear local storage for the current session, with
    the datasets the dataset jobs computed."""
    jobs = await jobs_db.list_jobs(session_id)
    await jobs_db.delete_all_jobs(session_id)
    for job in jobs:
        await run_in_threadpool(_delete_dataset_of, job, session_id)
    await broadcast_jobs_update()
    return {"status": "all deleted"}


@router.get("/progress/{task_id}")
async def get_task_progress(task_id: str, session_id: str = Depends(get_session_id)) -> dict[str, Any]:
    """Get active progress percentage and status of a running job."""
    validate_job_id(task_id)
    job = await jobs_db.read_job(task_id, session_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")
    return {
        "percentage": job.get("percentage", 0.0),
        "status": job.get("progress_status", "Pending..."),
        "aborted": job.get("status") == "aborted"
    }


@router.post("/progress/{task_id}/abort")
async def abort_task(task_id: str, session_id: str = Depends(get_session_id)) -> dict[str, str]:
    """Request cooperative cancellation of a running job."""
    validate_job_id(task_id)
    job = await jobs_db.read_job(task_id, session_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")
    await jobs_db.update_job_progress(task_id, job.get("percentage", 0.0), "Aborted by user", status="aborted")
    return {"status": "abort requested"}


@router.get("/jobs/{job_id}/download")
async def download_job_results_zip(job_id: str, session_id: str = Depends(get_session_id)) -> StreamingResponse:
    """Download ZIP containing all artifacts generated by a job."""
    validate_job_id(job_id)
    job = await jobs_db.read_job(job_id, session_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")
    return await _download_job_artifacts(job_id)


@router.patch("/jobs/{job_id}/notes")
async def update_notes(
    job_id: str,
    payload: NotesUpdate,
    session_id: str = Depends(get_session_id),
) -> dict[str, Any]:
    """Set or clear the free-text note on a run."""
    validate_job_id(job_id)
    ok = await jobs_db.update_job_notes(job_id, payload.notes, session_id)
    if not ok:
        raise HTTPException(status_code=404, detail="Job not found")
    # Notify any SSE listeners so the Run History view can reflect the
    # update without a page reload.
    await broadcast_jobs_update()
    return {"status": "updated", "notes": payload.notes}

